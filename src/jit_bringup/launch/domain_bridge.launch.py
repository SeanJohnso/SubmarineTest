#!/usr/bin/env python3
"""One launch for the sub: domain bridge, then MAVROS, then the jit stack.

    ros2 launch jit_bringup domain_bridge.launch.py
    ros2 launch jit_bringup domain_bridge.launch.py waypoint_source:=task
    ros2 launch jit_bringup domain_bridge.launch.py start_stack:=false   # bridge + MAVROS only

Any jit_bringup.launch.py or mavros.launch.py argument can be given here and is
passed through (waypoint_source, enable_survey, fcu_url, ...).

EVERYTHING COMES FROM config/domain_bridge.yaml
-----------------------------------------------
- ``from_domain`` (56) is the shared domain of the boat and the other robots.
- ``to_domain`` (77) is the sub's private domain. This launch sets
  ROS_DOMAIN_ID to it for every process it starts, so no export is needed.
- ``topics`` are what the bridge carries across.
- ``network.allowed_addresses`` are the only addresses Fast DDS may use for UDP.
  This launch writes a Fast DDS profile from them and applies it to the bridge,
  MAVROS and the stack, so none of their DDS traffic, on either domain, goes
  out on wlan0. Same-host traffic still uses shared memory.

START ORDER
-----------
The bridge starts first, MAVROS ``mavros_delay_s`` later, and the stack
``stack_delay_s`` after the launch began. Timers, not process-start events:
the bridge respawns, and a respawn must not start a second MAVROS or stack.

Ctrl-C stops all three. If gpio_estop_node fails, jit_bringup shuts the whole
launch down, MAVROS and the bridge included.

Run only one bridge: two bridges pass /tf_static back and forth between each
other. Needs ``sudo apt install ros-humble-domain-bridge``.
"""

import os
import tempfile

import yaml
from launch import LaunchDescription
from launch.actions import (
    DeclareLaunchArgument,
    IncludeLaunchDescription,
    LogInfo,
    OpaqueFunction,
    SetEnvironmentVariable,
    TimerAction,
)
from launch.conditions import IfCondition
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import LaunchConfiguration, PathJoinSubstitution
from launch_ros.actions import Node
from launch_ros.substitutions import FindPackageShare

RESPAWN_DELAY_S = 2.0

PROFILE_TEMPLATE = """<?xml version="1.0" encoding="UTF-8" ?>
<!-- Generated by jit_bringup domain_bridge.launch.py from {source}. Do not edit. -->
<profiles xmlns="http://www.eprosima.com/XMLSchemas/fastRTPS_Profiles">
  <transport_descriptors>
    <transport_descriptor>
      <transport_id>whitelisted_udp</transport_id>
      <type>UDPv4</type>
      <interfaceWhiteList>
{addresses}
      </interfaceWhiteList>
    </transport_descriptor>
    <transport_descriptor>
      <transport_id>shm</transport_id>
      <type>SHM</type>
    </transport_descriptor>
  </transport_descriptors>
  <participant profile_name="jit_whitelisted" is_default_profile="true">
    <rtps>
      <userTransports>
        <transport_id>shm</transport_id>
        <transport_id>whitelisted_udp</transport_id>
      </userTransports>
      <useBuiltinTransports>false</useBuiltinTransports>
    </rtps>
  </participant>
</profiles>
"""


def write_profile(path, source, addresses):
    lines = "\n".join("        <address>{}</address>".format(a) for a in addresses)
    with open(path, "w") as f:
        f.write(PROFILE_TEMPLATE.format(source=source, addresses=lines))


def setup(context):
    """Read domain_bridge.yaml, write the DDS profile, set the environment."""
    config_path = LaunchConfiguration("bridge_config").perform(context)
    with open(config_path) as f:
        config = yaml.safe_load(f)

    private = int(config["to_domain"])
    addresses = [str(a) for a in (config.get("network") or {}).get("allowed_addresses", [])]

    actions = [SetEnvironmentVariable("ROS_DOMAIN_ID", str(private))]

    rmw = os.environ.get("RMW_IMPLEMENTATION", "rmw_fastrtps_cpp")
    if rmw != "rmw_fastrtps_cpp":
        actions.append(LogInfo(
            msg="[sub] WARNING: RMW_IMPLEMENTATION is {}. The interface restriction "
                "is a Fast DDS profile and does nothing with it - DDS traffic may "
                "go out on wlan0.".format(rmw)))

    out_dir = tempfile.mkdtemp(prefix="jit_dds_")
    default_profile = os.path.join(out_dir, "whitelisted.xml")
    write_profile(default_profile, config_path, addresses)
    actions += [
        SetEnvironmentVariable("FASTRTPS_DEFAULT_PROFILES_FILE", default_profile),
        LogInfo(msg="[sub] ROS_DOMAIN_ID={} (bridged to {}). DDS limited to {}; "
                    "profile in {}.".format(private, config["from_domain"],
                                             ", ".join(addresses), out_dir)),
    ]

    return actions


def generate_launch_description():
    share = FindPackageShare("jit_bringup")
    args = [
        DeclareLaunchArgument(
            "bridge_config",
            default_value=PathJoinSubstitution([share, "config", "domain_bridge.yaml"]),
            description="Domains, bridged topics and allowed network addresses."),
        DeclareLaunchArgument(
            "start_mavros", default_value="true",
            description="Start mavros.launch.py after the bridge."),
        DeclareLaunchArgument(
            "start_stack", default_value="true",
            description="Start jit_bringup.launch.py after MAVROS."),
        DeclareLaunchArgument(
            "mavros_delay_s", default_value="2.0",
            description="Seconds after launch before MAVROS starts."),
        DeclareLaunchArgument(
            "stack_delay_s", default_value="6.0",
            description="Seconds after launch before the stack starts."),
    ]

    # No name=: the process holds one node per domain, named from the config's
    # "name" (jit_bridge_56, jit_bridge_77), and a launch name would remap both.
    # The domains come from the YAML.
    bridge = Node(
        package="domain_bridge", executable="domain_bridge",
        arguments=[LaunchConfiguration("bridge_config")],
        output="screen", respawn=True, respawn_delay=RESPAWN_DELAY_S,
    )

    mavros = TimerAction(
        period=LaunchConfiguration("mavros_delay_s"),
        actions=[IncludeLaunchDescription(PythonLaunchDescriptionSource(
            PathJoinSubstitution([share, "launch", "mavros.launch.py"])))],
        condition=IfCondition(LaunchConfiguration("start_mavros")),
    )

    stack = TimerAction(
        period=LaunchConfiguration("stack_delay_s"),
        actions=[IncludeLaunchDescription(PythonLaunchDescriptionSource(
            PathJoinSubstitution([share, "launch", "jit_bringup.launch.py"])))],
        condition=IfCondition(LaunchConfiguration("start_stack")),
    )

    return LaunchDescription(args + [OpaqueFunction(function=setup), bridge, mavros, stack])
