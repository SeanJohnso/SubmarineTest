"""Per-run network setup shared by the sub's three launch files.

domain_bridge.launch.py, mavros.launch.py and jit_bringup.launch.py each start
with ``network_setup()``, so every process they start gets the same settings,
taken from config/domain_bridge.yaml:

- ROS_DOMAIN_ID = ``to_domain`` (77), the sub's private domain. No export is
  needed in the shell.
- FASTRTPS_DEFAULT_PROFILES_FILE = a Fast DDS profile that allows UDP only on
  ``network.allowed_addresses`` (loopback and eth0), plus shared memory. No DDS
  traffic, on either domain, goes out on wlan0.

The profile is written to the same path by every launch, from the same YAML,
so all three use identical settings.

Not a launch file itself: the launch files import it from their own directory.
"""

import os
import tempfile

import yaml
from ament_index_python.packages import get_package_share_directory
from launch.actions import LogInfo, OpaqueFunction, SetEnvironmentVariable

PROFILE_TEMPLATE = """<?xml version="1.0" encoding="UTF-8" ?>
<!-- Generated by jit_bringup jit_network.py from {source}. Do not edit. -->
<profiles xmlns="http://www.eprosima.com/XMLSchemas/fastRTPS_Profiles">
  <transport_descriptors>
    <transport_descriptor>
      <transport_id>whitelisted_udp</transport_id>
      <type>UDPv4</type>
      <interfaceWhiteList>
{addresses}
      </interfaceWhiteList>
    </transport_descriptor>
    <transport_descriptor>
      <transport_id>shm</transport_id>
      <type>SHM</type>
    </transport_descriptor>
  </transport_descriptors>
  <participant profile_name="jit_whitelisted" is_default_profile="true">
    <rtps>
      <userTransports>
        <transport_id>shm</transport_id>
        <transport_id>whitelisted_udp</transport_id>
      </userTransports>
      <useBuiltinTransports>false</useBuiltinTransports>
    </rtps>
  </participant>
</profiles>
"""


def config_path(context):
    """The bridge YAML: bridge_config if a launch set it, else the package copy."""
    return context.launch_configurations.get("bridge_config") or os.path.join(
        get_package_share_directory("jit_bringup"), "config", "domain_bridge.yaml")


def _write_profile(path, source, addresses):
    lines = "\n".join("        <address>{}</address>".format(a) for a in addresses)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    # Written to a temp file and renamed, so a launch starting at the same time
    # never reads a half-written profile.
    tmp = "{}.{}".format(path, os.getpid())
    with open(tmp, "w") as f:
        f.write(PROFILE_TEMPLATE.format(source=source, addresses=lines))
    os.replace(tmp, path)


def _setup(context, tag):
    path = config_path(context)
    with open(path) as f:
        config = yaml.safe_load(f)

    domain = int(config["to_domain"])
    addresses = [str(a) for a in (config.get("network") or {}).get("allowed_addresses", [])]
    profile = os.path.join(
        tempfile.gettempdir(), "jit_dds_{}".format(os.getuid()), "whitelisted.xml")
    _write_profile(profile, path, addresses)

    actions = [
        SetEnvironmentVariable("ROS_DOMAIN_ID", str(domain)),
        SetEnvironmentVariable("FASTRTPS_DEFAULT_PROFILES_FILE", profile),
        LogInfo(msg="[{}] ROS_DOMAIN_ID={}, DDS limited to {} (from {}).".format(
            tag, domain, ", ".join(addresses) or "all interfaces", path)),
    ]
    rmw = os.environ.get("RMW_IMPLEMENTATION", "rmw_fastrtps_cpp")
    if rmw != "rmw_fastrtps_cpp":
        actions.append(LogInfo(
            msg="[{}] WARNING: RMW_IMPLEMENTATION is {}. The address restriction is a "
                "Fast DDS profile and does nothing with it - DDS may use wlan0."
                .format(tag, rmw)))
    return actions


def network_setup(tag):
    """An action that applies the setup. Put it first in the LaunchDescription."""
    return OpaqueFunction(function=_setup, kwargs={"tag": tag})
